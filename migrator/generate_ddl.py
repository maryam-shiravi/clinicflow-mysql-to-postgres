"""
Phase 2, Step 6: read the MySQL schema (read-only) and GENERATE PostgreSQL DDL.
Nothing is executed against Postgres; we only write a .sql file to review.
"""
import re
from getpass import getpass
from pathlib import Path
import mysql.connector

SOURCE_DB = "clinicflow_legacy"

# Text columns that really hold dates (decision #9). Later this moves to a config file.
DATE_COLUMNS = {
    ("People", "birth_date"),
    ("Employees", "hire_date"),
    ("Patients", "diagnosisDate"),
    ("Appointments", "apptDate"),
    ("HealthDocuments", "result_date"),
    ("Costs", "cost_date"),
}

QUARANTINE_SQL = """CREATE TABLE migration_quarantine (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  source_table text NOT NULL,
  source_row_id bigint NOT NULL,
  source_column text NOT NULL,
  original_value text,
  reason text NOT NULL,
  quarantined_at timestamptz NOT NULL DEFAULT now()
);"""


def snake(name):
    """firstName -> first_name, HealthDocuments -> health_documents"""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).lower()


def s(v):
    """The connector sometimes returns bytes for metadata text; normalise to str."""
    return v.decode() if isinstance(v, (bytes, bytearray)) else v


def fetch_columns(conn):
    cur = conn.cursor(dictionary=True)
    # Aliases force lowercase keys (MySQL 8 returns UPPERCASE names for information_schema).
    cur.execute("""
        SELECT table_name AS table_name, column_name AS column_name,
               data_type AS data_type, column_type AS column_type,
               is_nullable AS is_nullable, numeric_precision AS numeric_precision,
               numeric_scale AS numeric_scale, column_key AS column_key,
               column_default AS column_default, extra AS extra
        FROM information_schema.columns
        WHERE table_schema = %s
        ORDER BY table_name, ordinal_position
    """, (SOURCE_DB,))
    rows = cur.fetchall()
    cur.close()
    return [{k: s(v) for k, v in r.items()} for r in rows]


def pg_type(col, enum_name):
    t = col["data_type"]
    if (col["table_name"], col["column_name"]) in DATE_COLUMNS:
        return "date"
    if t == "int":
        return "integer"
    if t in ("varchar", "text"):
        return "text"
    if t == "tinyint":
        return "boolean"   # only safe because we verified the columns hold just 0/1
    if t == "enum":
        return enum_name
    if t == "decimal":
        return f"numeric({col['numeric_precision']},{col['numeric_scale']})"
    if t == "datetime":
        return "timestamptz"
    raise ValueError(f"No mapping rule for MySQL type {t!r} "
                     f"({col['table_name']}.{col['column_name']})")


def pg_default(col, base_type):
    d, extra = col["column_default"], col["extra"] or ""
    if d is None:
        return None
    if "DEFAULT_GENERATED" in extra and str(d).upper().startswith("CURRENT_TIMESTAMP"):
        return "now()"
    if base_type == "boolean":
        return "TRUE" if str(d) in ("1", "true") else "FALSE"
    if base_type == "integer" or base_type.startswith("numeric"):
        return str(d)
    return "'" + str(d).replace("'", "''") + "'"


def build_ddl(cols):
    tables = {}
    for c in cols:
        tables.setdefault(c["table_name"], []).append(c)

    enum_sql, table_sql = [], []
    for tname, tcols in tables.items():
        lines, pk = [], []
        for c in tcols:
            cname = snake(c["column_name"])
            enum_name = f"{snake(tname)}_{cname}"
            if c["data_type"] == "enum":
                values = re.findall(r"'([^']*)'", c["column_type"])
                vals = ", ".join("'" + v.replace("'", "''") + "'" for v in values)
                enum_sql.append(f"CREATE TYPE {enum_name} AS ENUM ({vals});")
            base = pg_type(c, enum_name)
            line = f"  {cname} {base}"
            if "auto_increment" in (c["extra"] or ""):
                line += " GENERATED BY DEFAULT AS IDENTITY"
            if c["is_nullable"] == "NO":
                line += " NOT NULL"
            dflt = pg_default(c, base)
            if dflt is not None:
                line += f" DEFAULT {dflt}"
            if c["column_key"] == "PRI":
                pk.append(cname)
            lines.append(line)
        if pk:
            lines.append(f"  PRIMARY KEY ({', '.join(pk)})")
        table_sql.append(f"CREATE TABLE {snake(tname)} (\n" + ",\n".join(lines) + "\n);")
    return enum_sql, table_sql


if __name__ == "__main__":
    conn = mysql.connector.connect(
        host="localhost", user="migrator_ro",
        password=getpass("MySQL (migrator_ro) password: "), database=SOURCE_DB)
    cols = fetch_columns(conn)
    conn.close()

    enum_sql, table_sql = build_ddl(cols)
    text = ("-- Generated by migrator/generate_ddl.py from MySQL clinicflow_legacy\n\n"
            + "\n\n".join(enum_sql + table_sql + [QUARANTINE_SQL]) + "\n")

    out = Path("migrator/out")
    out.mkdir(parents=True, exist_ok=True)
    (out / "schema_pg.sql").write_text(text)
    print(text)
